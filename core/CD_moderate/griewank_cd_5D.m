T_break = [NaN -1.5665904587714294 NaN 2.5993169512703389 NaN];   % breakpoints of T (NaN for continuous)
T_image = [NaN 0 NaN 0 NaN];   % their images
m = 151;
ProblemData = cell(1, 5);
ProblemData{1} = [lb_C_work(1); ub_C_work(1)];
ProblemData{2} = {linspace(lb_orig(2), ub_orig(2), m)'};
ProblemData{3} = [lb_C_work(3); ub_C_work(3)];
ProblemData{4} = {linspace(lb_orig(4), ub_orig(4), m)'};
ProblemData{5} = [lb_C_work(5); ub_C_work(5)];
PB.name        = 'griewank_cd_5D';
PB.base_function = 'griewank';
PB.suite_version = 2;
PB.core = true;
PB.suite_release = '2.1.0';
PB.description = 'DFO Benchmark Suite v2.1.0 core: CD adaptation of griewank (F = f o T).';
PB.nvar        = 5;
PB.nobj        = 1;
PB.var_types   = {'C','D','C','D','C'};
PB.type_counts = struct('C', 3, 'D', 2, 'K', 0);
PB.proportion  = [3 2 0];
PB.pattern     = 'CD';
PB.strategy    = 'moderate';
PB.scale_factors_C = [1 100 0.01];
PB.cardinality = [Inf 151 Inf 151 Inf];
PB.n_finite    = 2;
PB.finite_part_size = 22801;
PB.M_K = 1;
PB.domain_size = Inf;
PB.lb_orig = lb_orig(:); PB.ub_orig = ub_orig(:);
PB.lb_C_work = lb_C_work(:); PB.ub_C_work = ub_C_work(:);
PB.m = m;
PB.ProblemData = ProblemData;
D = struct('name', 'griewank_cd_5D', 'm', m, 'lb', lb_orig(:), 'ub', ub_orig(:), 'lbw', lb_C_work(:), 'ubw', ub_C_work(:), 'Tb', T_break(:), 'Ti', T_image(:));
D.E = cell(1, 5);
D.cw = [0 NaN 0 NaN 0];   % anchors of the continuous maps (NaN for finite)
D.cx = [0 NaN 0 NaN 0];
D.fn = @(xh) griewank_orig(xh);
PB.f_star      = 0;
PB.f_star_justification = 'E';   % exact by structure
PB.n_minimizers_documented = 1;
PB.x0_idx      = [362.06396055221558 48 36982.042607616007 44 -5.5240209592249174];   % protocol starting point: Halton point 1023 (index representation)
PB.x0_alt_idx  = [-133.07452940940857 37 -7705.408733183991 26 2.2049720362180842;115.20004105567932 41 56738.600042496008 33 -0.94555590034079362;-370.06389212608337 51 12051.148701695995 39 -4.0960838368996715;239.33732628822327 39 -37152.087195647997 25 3.6329091585433311;-251.56921076774597 43 31055.07537715201 31 0.39996060886322571;-3.2946403026580811 47 -17395.529760767997 35 -1.8439405833621612;-488.55857348442078 34 50811.63281203201 41 -4.9944685199210381;301.40596890449524 44 2361.0276741120033 27 2.7345244755219635;-192.32187008857727 48 -23510.654681087995 34 -0.41600346103691521];   % 9 alternative starting points (Halton indices 1023 + 63 k)
PB.core_pidx   = 23;
PB.func_idx    = @(z) objective(z, D);
PB.func_F      = @(xr) objective(cell2idx(xr, PB), D);
PB.idx2cell    = @(z) idx2cell(z, PB);
