function xh = decode_to_original(z, D)
if ~isnumeric(z) || numel(z) ~= 10 || ~all(isfinite(z)), error('griewank_cdk_10D: z must be a finite numeric vector with 10 entries.'); end
xh = zeros(10, 1);
